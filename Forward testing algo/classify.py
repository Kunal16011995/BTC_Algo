"""Classify existing forward-test trades as FVG-aligned under current strategy rules."""
from __future__ import annotations

import json
import logging
from datetime import datetime, timezone

import pandas as pd

import config
import store
from bybit_client import BybitClient
from strategy import Direction, generate_setups

log = logging.getLogger("classify")

PARAMS = {
    "stop_pct": 0.004,
    "tp1_pct": 0.004,
    "runner_a_pct": 0.020,
    "runner_a_plus_pct": 0.040,
    "htf_proximity_pct": 0.003,
    "fvg_lookforward": 8,
    "a_body_threshold": 0.52,
    "a_plus_body_threshold": 0.70,
    "tp2_a_pct": 0.015,
    "tp2_a_plus_pct": 0.025,
}

SYMBOL = "BTCUSDT"


def _klines_to_df(rows: list) -> pd.DataFrame:
    rows = sorted(rows, key=lambda r: int(r[0]))
    df = pd.DataFrame(
        rows,
        columns=["open_time", "open", "high", "low", "close", "volume", "turnover"],
    )
    df["timestamp"] = pd.to_datetime(df["open_time"].astype(float), unit="ms", utc=True)
    for col in ["open", "high", "low", "close", "volume", "turnover"]:
        df[col] = df[col].astype(float)
    return df[["timestamp", "open", "high", "low", "close", "volume", "turnover"]]


def _resample_m15_to_h1(m15: pd.DataFrame, h1_bars: int = 100) -> pd.DataFrame:
    df = m15.set_index("timestamp").copy()
    h1 = (
        df.resample("h")
        .agg({
            "open": "first",
            "high": "max",
            "low": "min",
            "close": "last",
            "volume": "sum",
            "turnover": "sum",
        })
        .dropna()
        .reset_index()
    )
    return h1.tail(h1_bars).reset_index(drop=True)


def _entry_time_ms(trade: dict) -> int:
    """Extract entry timestamp from trade raw data."""
    raw = trade.get("raw", {}) or {}
    if isinstance(raw, str):
        try:
            raw = json.loads(raw)
        except Exception:
            raw = {}
    # Live closed-PnL rows carry createdTime of the closing order, which equals entry
    # time because SL/TP orders are attached at entry.
    created = raw.get("createdTime")
    if created:
        return int(created)
    # Fallback: use exit time (less accurate, but still useful for classification window).
    return int(trade.get("exit_ts", 0) or 0)


def _is_paper_trade(trade: dict) -> bool:
    """Paper trades generated by current code carry exit_reason in raw."""
    raw = trade.get("raw", {}) or {}
    if isinstance(raw, str):
        try:
            raw = json.loads(raw)
        except Exception:
            raw = {}
    return "exit_reason" in raw


def classify_trades(client: BybitClient | None = None) -> dict[str, bool]:
    """Return {trade_id: fvg_aligned} for all tight forward-test trades."""
    if client is None:
        client = BybitClient(
            config.BYBIT_API_KEY,
            config.BYBIT_API_SECRET,
            config.BYBIT_DEMO_BASE_URL,
            config.BYBIT_PUBLIC_BASE_URL,
        )

    store.init()
    trades = store.load_trades_variant("tight")
    if not trades:
        return {}

    # Separate paper (always aligned) and live trades.
    result: dict[str, bool] = {}
    live_trades: list[dict] = []
    for t in trades:
        if _is_paper_trade(t):
            result[t["id"]] = True
        else:
            live_trades.append(t)

    if not live_trades:
        return result

    entry_times = [_entry_time_ms(t) for t in live_trades]
    min_ms = min(t for t in entry_times if t)
    max_ms = max(t for t in entry_times if t)

    # Fetch enough history so the leg lookback is covered at the edges.
    fetch_start = min_ms - 3 * 24 * 60 * 60 * 1000
    fetch_end = max_ms + 3 * 24 * 60 * 60 * 1000
    now_ms = int(datetime.now(timezone.utc).timestamp() * 1000)
    fetch_end = min(fetch_end, now_ms)

    log.info("Fetching M15 history for classification: %s to %s", fetch_start, fetch_end)
    rows = client.get_all_klines(SYMBOL, "15", start_ms=fetch_start, end_ms=fetch_end)
    m15 = _klines_to_df(rows)
    # Match the corrected bot: evaluate setups only on completed bars.
    if len(m15) > 1:
        m15 = m15.iloc[:-1].copy().reset_index(drop=True)
    h1 = _resample_m15_to_h1(m15)
    log.info("M15 bars=%d H1 bars=%d", len(m15), len(h1))

    setups = generate_setups(m15.copy(), h1.copy(), **PARAMS)
    log.info("Generated %d strategy setups", len(setups))

    bar_ms = 15 * 60 * 1000
    for t in live_trades:
        entry_ms = _entry_time_ms(t)
        entry_ts = pd.to_datetime(entry_ms, unit="ms", utc=True)
        # The corrected bot places the order just after a 15-minute bar boundary,
        # processing the bar that just closed.  The setup timestamp is therefore
        # the bar immediately preceding the order time, not the order time itself.
        expected_setup_ms = ((entry_ms // bar_ms) - 1) * bar_ms
        expected_setup_ts = pd.to_datetime(expected_setup_ms, unit="ms", utc=True)
        side = t.get("side", "")
        entry_price = float(t.get("entry_price", 0) or 0)

        aligned = False
        for s in setups:
            if s.direction == Direction.LONG and side != "Buy":
                continue
            if s.direction == Direction.SHORT and side != "Sell":
                continue
            if abs((s.timestamp - expected_setup_ts).total_seconds()) > 7.5 * 60:
                continue
            if entry_price > 0 and abs(s.entry_price - entry_price) / entry_price > 0.003:
                continue
            aligned = True
            break

        result[t["id"]] = aligned
        log.info(
            "%s entry=%s setup_ts=%s %s price=%.2f -> fvg_aligned=%s",
            t["id"][:30],
            entry_ts.strftime("%Y-%m-%d %H:%M UTC"),
            expected_setup_ts.strftime("%Y-%m-%d %H:%M UTC"),
            side,
            entry_price,
            aligned,
        )

    return result


def save_classification(aligned_map: dict[str, bool]):
    store.set_meta("fvg_aligned_trade_ids", json.dumps(aligned_map))


def load_classification() -> dict[str, bool]:
    raw = store.get_meta("fvg_aligned_trade_ids", "")
    if not raw:
        return {}
    try:
        return json.loads(raw)
    except Exception:
        return {}


def ensure_classification(client: BybitClient | None = None) -> dict[str, bool]:
    """Load cached classification, adding any new/missing trades."""
    cached = load_classification()
    store.init()
    trades = store.load_trades_variant("tight")
    missing = [t for t in trades if t["id"] not in cached]
    if missing:
        log.info("Classifying %d new/missing trades", len(missing))
        new_map = classify_trades(client)
        cached.update(new_map)
        save_classification(cached)
    return cached


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(asctime)s | %(levelname)-8s | %(message)s")
    aligned = classify_trades()
    save_classification(aligned)
    print(json.dumps(aligned, indent=2, default=str))
